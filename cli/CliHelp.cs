        writer.WriteLine();
        writer.WriteLine("可选参数");
        writer.WriteLine("  -h, --help          显示本帮助并退出");
        writer.WriteLine("  -scale <N>          推理倍率，必须符合模型原生倍率；默认读取模型能力");
        writer.WriteLine("  -output-scale <N>   目标输出倍率（1–8）；超分结果先调整尺寸（TRT 图内缩小 / 其余 Lanczos），默认原生");
